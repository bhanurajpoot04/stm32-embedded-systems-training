static void lcd_enable_pulse(void)
{
    HAL_GPIO_WritePin(LCD_EN_GPIO_Port, LCD_EN_Pin, GPIO_PIN_SET);
    HAL_Delay(1);
    HAL_GPIO_WritePin(LCD_EN_GPIO_Port, LCD_EN_Pin, GPIO_PIN_RESET);
    HAL_Delay(1);
}

static void lcd_send4(uint8_t nibble)
{
    HAL_GPIO_WritePin(LCD_D4_GPIO_Port, LCD_D4_Pin, (nibble & 0x01) ? GPIO_PIN_SET : GPIO_PIN_RESET);
    HAL_GPIO_WritePin(LCD_D5_GPIO_Port, LCD_D5_Pin, (nibble & 0x02) ? GPIO_PIN_SET : GPIO_PIN_RESET);
    HAL_GPIO_WritePin(LCD_D6_GPIO_Port, LCD_D6_Pin, (nibble & 0x04) ? GPIO_PIN_SET : GPIO_PIN_RESET);
    HAL_GPIO_WritePin(LCD_D7_GPIO_Port, LCD_D7_Pin, (nibble & 0x08) ? GPIO_PIN_SET : GPIO_PIN_RESET);
    lcd_enable_pulse();
}

void lcd_cmd(uint8_t cmd)
{
    HAL_GPIO_WritePin(LCD_RS_GPIO_Port, LCD_RS_Pin, GPIO_PIN_RESET);
    lcd_send4(cmd >> 4);
    lcd_send4(cmd & 0x0F);
    HAL_Delay(2);
}

void lcd_data(uint8_t data)
{
    HAL_GPIO_WritePin(LCD_RS_GPIO_Port, LCD_RS_Pin, GPIO_PIN_SET);
    lcd_send4(data >> 4);
    lcd_send4(data & 0x0F);
    HAL_Delay(1);
}

void lcd_goto(uint8_t row, uint8_t col)
{
    uint8_t address = (row == 0) ? (0x80 + col) : (0xC0 + col);
    lcd_cmd(address);
}

void lcd_puts(char *str)
{
    while (*str)
    {
        lcd_data((uint8_t)*str);
        str++;
    }
}

void lcd_init(void)
{
    HAL_Delay(50);
    HAL_GPIO_WritePin(LCD_RS_GPIO_Port, LCD_RS_Pin, GPIO_PIN_RESET);

    lcd_send4(0x03);
    HAL_Delay(5);
    lcd_send4(0x03);
    HAL_Delay(1);
    lcd_send4(0x03);
    HAL_Delay(1);
    lcd_send4(0x02);
    HAL_Delay(1);

    lcd_cmd(0x28);   // 4-bit, 2-line, 5x8 font
    lcd_cmd(0x0C);   // display ON, cursor OFF
    lcd_cmd(0x06);   // entry mode
    lcd_cmd(0x01);   // clear
    HAL_Delay(5);
}

